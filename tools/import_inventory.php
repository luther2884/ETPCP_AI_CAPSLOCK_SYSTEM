function ensureCategory(PDO $pdo, string $name, ?string $description = null, ?string $imageUrl = null): int {
    $stmt = $pdo->prepare("SELECT id FROM categories WHERE name = ?");
    $stmt->execute([$name]);
    $id = $stmt->fetchColumn();
    if ($id) {
        return (int)$id;
    }
    $stmt = $pdo->prepare("INSERT INTO categories (name, description, image_url) VALUES (?, ?, ?)");
    $stmt->execute([$name, $description, $imageUrl]);
    return (int)$pdo->lastInsertId();
}

function upsertProduct(PDO $pdo, array $p): int {
    // $p: ['name'=>, 'stock'=>, 'category_id'=>, 'price'=>, 'image_url'=>]
    $stmt = $pdo->prepare("SELECT id, price FROM products WHERE name = ? LIMIT 1");
    $stmt->execute([$p['name']]);
    $existing = $stmt->fetch();
    if ($existing) {
        // Preserve existing price if non-zero
        $price = ($existing['price'] ?? 0) > 0 ? $existing['price'] : $p['price'];
        $upd = $pdo->prepare("UPDATE products SET stock = ?, category_id = ?, price = ?, image_url = COALESCE(?, image_url), status='active', updated_at = NOW() WHERE id = ?");
        $upd->execute([(int)$p['stock'], (int)$p['category_id'], $price, $p['image_url'], (int)$existing['id']]);
        return (int)$existing['id'];
    }
    $ins = $pdo->prepare("INSERT INTO products (name, description, price, stock, category_id, image_url, status) VALUES (?, ?, ?, ?, ?, ?, 'active')");
    $ins->execute([$p['name'], $p['description'] ?? null, $p['price'], (int)$p['stock'], (int)$p['category_id'], $p['image_url']]);
    return (int)$pdo->lastInsertId();
}

